/** 같은 내용을 Markdown으로 만든다 (`docs/USER_GUIDE.md`). */
export function guideToMarkdown(sections: GuideSection[] = GUIDE): string {
  const cell = (s: string) => s.replace(/\|/g, "\\|");
  const out: string[] = [
    `# ${GUIDE_TITLE}`,
    "",
    "> 이 파일은 `apps/web/src/features/guide/content.ts`에서 생성됩니다. 앱에서는 `/guide` 페이지로 볼 수 있습니다.",
    "> 직접 고치지 말고 원본을 고친 뒤 `cd apps/web && STAYOPS_WRITE_GUIDE=true pnpm test guide`를 실행하세요.",
    "",
    GUIDE_SUMMARY,
    "",
    "## 목차",
    ...sections.map((s) => `- [${s.title}](#${s.id})`),
  ];
  for (const s of sections) {
    out.push("", `<a id="${s.id}"></a>`, "", `## ${s.title}`);
    for (const b of s.blocks) {
      out.push("");
      switch (b.kind) {
        case "p":
          out.push(b.text);
          break;
        case "h3":
          out.push(`### ${b.text}`);
          break;
        case "note":
          out.push(`> ${b.text}`);
          break;
        case "list":
          out.push(...b.items.map((i) => `- ${i}`));
          break;
        case "steps":
          out.push(...b.items.map((i, n) => `${n + 1}. ${i}`));
          break;
        case "table":
          out.push(`| ${b.head.map(cell).join(" | ")} |`, `|${b.head.map(() => "---").join("|")}|`, ...b.rows.map((r) => `| ${r.map(cell).join(" | ")} |`));
          break;
      }
    }
  }
  return out.join("\n") + "\n";
}
